"""Compile reviewed PO entries into a small read-only C++ catalogue.

GNU msgfmt handles PO syntax, fuzzy entries and printf validation; Python's
standard gettext reader handles the compiled catalogue. No custom PO parser.
"""
import argparse
from collections import Counter
import gettext
import hashlib
import json
from pathlib import Path
from python_compat import pgettext, is_relative_to
import re
import shutil
import subprocess
import tempfile
from source_hash import text_file_sha256


def generate(manifest, po, output):
    msgfmt = shutil.which('msgfmt')
    if not msgfmt:
        raise SystemExit('msgfmt not found: install the MSYS2 gettext package.')
    entries = json.loads(manifest.read_text(encoding='utf-8'))['messages']
    with tempfile.TemporaryDirectory() as tmp:
        mo = Path(tmp) / 'ui.mo'
        subprocess.run([msgfmt, '--check', '--check-format', '-o', str(mo),
                        str(po)], check=True)
        with mo.open('rb') as stream:
            translations = gettext.GNUTranslations(stream)
    rows = []
    seen = set()
    source_root = manifest.resolve().parents[2]
    # A catalogue contains many messages sharing the same code dependencies.
    # Read each dependency once per generation, while checking each entry's
    # expected hash separately. Never carry this cache across builds.
    dependency_hashes = {}
    for entry in entries:
        if entry['context'] in {'mon.cast.speech', 'x.speech', 'fix.shout',
                                'fix.charge', 'fix.cast', 'misc.lua.speech',
                                'misc.lua.reviewed'}:
            raise ValueError('TextDB prose belongs in textdb.po, not ui.po')
        key = (entry['context'], entry['english'])
        if key in seen:
            raise ValueError('Duplicate source message: ' + repr(key))
        seen.add(key)
        if entry['review_status'] != 'reviewed':
            continue
        # Complex expressions also depend on the code assembling their state
        # and arguments. Any changed dependency needs a fresh review; omit the
        # translation so the existing English branch remains available.
        dependencies_current = True
        for dependency in entry.get('source_dependencies', []):
            source = dependency['source']
            if source not in dependency_hashes:
                path = (source_root / source).resolve()
                dependency_hashes[source] = (
                    text_file_sha256(path)
                    if is_relative_to(path, source_root) and path.is_file()
                    else None)
            if (dependency_hashes[source] is None
                    or dependency_hashes[source] != dependency['sha256']):
                dependencies_current = False
                break
        if not dependencies_current:
            continue
        chinese = pgettext(translations, *key)
        if not chinese or chinese == entry['english']:
            continue
        # msgfmt checks c-format entries; also reject lost colour tags and
        # changed printf specifiers if an editor accidentally removes flags.
        patterns = [r'</?[A-Za-z][^>]*>']
        # A literal '%' hotkey followed by English prose ("% - List") can
        # resemble a printf conversion. Such menu labels declare this explicitly.
        patterns.append(r'%' if entry.get('literal_percent') else
                        r'%(?:[0-9]+\$)?[-+#0 .0-9*]*[hlLjzt]*[diuoxXfFeEgGaAcspn%]')
        for pattern in patterns:
            if Counter(re.findall(pattern, entry['english'])) != Counter(re.findall(pattern, chinese)):
                raise ValueError('Changed markup or printf arguments: ' + repr(key))
        # Only reviewed literal templates enter the binary. No Lua execution
        # and no substitution of rendered English or internal identifiers.
        # C++11 processes trigraphs before string escapes. A manual's "??"
        # key examples must remain byte-for-byte identical to its English key.
        rows.append('    {' + ', '.join(json.dumps(s, ensure_ascii=False).replace('?', r'\?')
                    for s in (*key, chinese)) + '},')
    text = ('// Generated by tools/localization/build_catalogue.py.\n'
            '#pragma once\n\n'
            'struct ui_catalogue_entry\n{\n'
            '    const char *context;\n    const char *english;\n'
            '    const char *chinese;\n};\n\n'
            'static const ui_catalogue_entry zh_ui_catalogue[] = {\n'
            + '\n'.join(rows) + '\n};\n')
    if not rows:
        # A sentinel keeps an empty/fuzzy-only catalogue valid C++11.
        text = text.replace('[] = {\n\n};', '[] = {\n    {"", "", ""},\n};')
    if not output.exists() or output.read_text(encoding='utf-8') != text:
        with output.open('w', encoding='utf-8', newline='\n') as stream:
            stream.write(text)
    else:
        # Satisfy make after a PO/manifest/tool update even if every changed
        # entry was fuzzy or unreviewed and the generated content is identical.
        output.touch()


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--manifest', required=True, type=Path)
    parser.add_argument('--po', required=True, type=Path)
    parser.add_argument('--output', required=True, type=Path)
    args = parser.parse_args()
    generate(args.manifest, args.po, args.output)
